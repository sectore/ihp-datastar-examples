-- | Generation counter, bumped per run so a stale run can notice a newer one and stop patching.
{-# NOINLINE rocketGenCounter #-}
rocketGenCounter :: IORef Int
rocketGenCounter = unsafePerformIO (newIORef 0)

-- | Fisher-Yates shuffle (`random` is already a transitive dep via IHP).
shuffleList :: forall a. [a] -> IO [a]
shuffleList xs = do
    arr <- newListArray (0, n - 1) xs :: IO (IOArray Int a)
    forM_ [n - 1, n - 2 .. 1] \i -> do
        j <- randomRIO (0, i)
        vi <- readArray arr i
        vj <- readArray arr j
        writeArray arr j vi
        writeArray arr i vj
    getElems arr
  where
    n = length xs

rocketPatchHtml :: Int -> Int -> Text -> Text
rocketPatchHtml row col hex =
    renderMarkupText [hsx|<div id={rocketCellId row col} class={pixelCellClass} style={"background-color: " <> hex}></div>|]

instance Controller RocketController where
    action RocketAction = render IndexView

    action RocketRunAction = respondAndExit $ sseResponseWith nullLogger compressors ?request $ \gen -> do
        myGeneration <- atomicModifyIORef' rocketGenCounter (\t -> (t + 1, t + 1))

        sendPatchElements gen (patchElements (renderMarkupText rocketGridHtml))

        shuffled <- shuffleList rocketPixels
        forM_ shuffled \(row, col, hex) -> do
            currentGeneration <- readIORef rocketGenCounter
            -- skip if a newer run has started
            when (currentGeneration == myGeneration) do
                sendPatchElements gen (patchElements (rocketPatchHtml row col hex))
                threadDelay (20 * 1000)
